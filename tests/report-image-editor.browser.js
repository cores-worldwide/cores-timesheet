async page => {
  const checks=[];
  const check=(ok,label)=>{if(!ok)throw new Error(label);checks.push(label);};
  const base='http://127.0.0.1:5212/cores-timesheet/report-builder/';
  await page.route('**/api/jobs',route=>route.fulfill({contentType:'application/json',body:'{"environment":"dev","jobs":[]}'}));
  await page.goto(base+'index.html');
  const original=await page.evaluate(()=>localStorage.getItem('cores-report-builder-mockup-v1'));
  const url=await page.evaluate(()=>{const c=document.createElement('canvas');c.width=400;c.height=200;const ctx=c.getContext('2d');ctx.fillStyle='#ff0000';ctx.fillRect(0,0,200,200);ctx.fillStyle='#0000ff';ctx.fillRect(200,0,200,200);return c.toDataURL('image/png');});
  await page.evaluate(url=>localStorage.setItem('cores-report-builder-mockup-v1',JSON.stringify({version:1,cover:{projectNo:'CROP-QA'},blocks:[{id:'crop-block',type:'media',title:'Image editing check',layout:'full',items:[{id:'crop-item',kind:'image',name:'crop-source.png',url,caption:'CROP CAPTION — Only the blue half should appear.'}]}]})),url);
  await page.reload();
  const dialog=page.getByRole('dialog',{name:'Edit image',exact:true});
  const open=async()=>{await page.getByRole('button',{name:'Edit image crop-source.png',exact:true}).first().click();await page.waitForFunction(()=>!document.querySelector('[data-image-save]').disabled);};
  const setSlider=async(selector,value)=>dialog.locator(selector).evaluate((el,value)=>{el.value=value;el.dispatchEvent(new Event('input',{bubbles:true}));},String(value));
  const stored=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('cores-report-builder-mockup-v1')).blocks[0].items[0]);
  await open();
  const bounds=await dialog.locator('.crop-surface').boundingBox();
  await page.mouse.move(bounds.x+bounds.width*.52,bounds.y+bounds.height*.03);
  await page.mouse.down();await page.mouse.move(bounds.x+bounds.width*.98,bounds.y+bounds.height*.97,{steps:8});await page.mouse.up();
  await dialog.locator('.precise-crop summary').click();
  check(Math.abs(Number(await dialog.getByRole('spinbutton',{name:'Crop width percent'}).inputValue())-46)<1,'Drawing on the original creates a crop rectangle');
  const selection=dialog.getByRole('group',{name:/Crop area/});
  await selection.focus();await page.keyboard.press('ArrowLeft');
  check(Number(await dialog.getByRole('spinbutton',{name:'Crop left percent'}).inputValue())<52,'Arrow keys reposition the crop');
  const handle=await dialog.locator('[data-crop-handle="se"]').boundingBox();
  await page.mouse.move(handle.x+handle.width/2,handle.y+handle.height/2);await page.mouse.down();await page.mouse.move(handle.x-15,handle.y-10,{steps:4});await page.mouse.up();
  check(Number(await dialog.getByRole('spinbutton',{name:'Crop width percent'}).inputValue())<46,'Corner handles resize the crop');
  await setSlider('[data-image-zoom]',200);
  check(await dialog.locator('[data-zoom-output]').innerText()==='200%','Zoom changes the cropped area');
  await setSlider('[data-image-position="x"]',100);
  check(Number(await dialog.getByRole('spinbutton',{name:'Crop left percent'}).inputValue())>=50,'Position controls move the crop across the source');
  await dialog.getByRole('button',{name:'Reset original',exact:true}).click();
  check(await dialog.getByRole('spinbutton',{name:'Crop width percent'}).inputValue()==='100.0','Reset restores the full original image');
  // Select exactly the blue half, then make it smaller in its report frame.
  for(const [name,value] of [['Crop width percent','50'],['Crop left percent','50']]){const input=dialog.getByRole('spinbutton',{name});await input.fill(value);await input.press('Tab');}
  await setSlider('[data-image-scale]',60);
  await dialog.screenshot({path:'tmp/pdfs/image-editor-dialog.png'});
  await dialog.getByRole('button',{name:'Apply image changes',exact:true}).click();
  await dialog.waitFor({state:'hidden'});
  const applied=await stored();
  check(applied.url===url,'Applying crop and resize leaves the original image data unchanged');
  check(applied.edit.crop.x===0.5&&applied.edit.crop.width===0.5&&applied.edit.scale===60,'Crop coordinates and size are saved in the draft');
  check(await page.locator('.media-frame .edited-image').getAttribute('viewBox')==='200 0 200 200','The report renders only the selected source rectangle');
  await page.locator('.media-frame').screenshot({path:'tmp/pdfs/image-crop-frame.png'});
  await open();
  check(await dialog.locator('[data-scale-output]').innerText()==='60%','Reopening restores the saved image size');
  await dialog.getByRole('button',{name:'Reset original',exact:true}).click();
  await dialog.getByRole('button',{name:'Cancel',exact:true}).click();
  check(JSON.stringify((await stored()).edit)===JSON.stringify(applied.edit),'Cancel discards unsaved image adjustments');
  await page.reload();
  check(await page.locator('.media-frame .edited-image').getAttribute('viewBox')==='200 0 200 200','Cropped report image survives reload');
  await page.emulateMedia({media:'print'});
  await page.pdf({path:'tmp/pdfs/image-crop-qa.pdf',format:'Letter',printBackground:true,preferCSSPageSize:true});
  await page.emulateMedia({media:'screen'});
  await open();
  await page.setViewportSize({width:390,height:844});
  check(await dialog.evaluate(el=>el.getBoundingClientRect().right<=innerWidth&&el.scrollWidth<=el.clientWidth+1),'Image editor fits a phone viewport');
  await dialog.getByRole('button',{name:'Reset original',exact:true}).click();
  await dialog.getByRole('button',{name:'Apply image changes',exact:true}).click();
  check((await stored()).edit.crop.width===1&&(await stored()).edit.scale===100,'Reset can be applied after reopening an edited image');
  await page.setViewportSize({width:1440,height:1000});
  await page.evaluate(original=>{if(original===null)localStorage.removeItem('cores-report-builder-mockup-v1');else localStorage.setItem('cores-report-builder-mockup-v1',original);},original);await page.reload();
  return {passed:checks.length,checks};
}
